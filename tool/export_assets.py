#!/usr/bin/env python3
"""Exports design/svg/** to PNGs at 1x/2x/3x and writes assets/manifest.json.

Requires rsvg-convert (brew install librsvg). Fonts are resolved from
assets/fonts through a private fontconfig file, so text renders in Fredoka.

Layout follows Flutter's resolution-aware convention:
  assets/images/<group>/<name>.png, .../2.0x/<name>.png, .../3.0x/<name>.png
Tinted icons go to assets/icons/.

Usage: python3 tool/export_assets.py [--check]
  --check  only verifies that every manifest file exists and nothing is unlisted.
"""
import concurrent.futures
import json
import os
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SVG = ROOT / 'design' / 'svg'
ASSETS = ROOT / 'assets'
MANIFEST = ASSETS / 'manifest.json'
AUDIO = ['dice_roll', 'dice_land', 'step', 'leave_base', 'capture', 'home', 'extra_roll', 'timer_tick', 'win', 'ui_tap',
         'music_loop']
AUDIO_SCREENS = {'music_loop': ['home', 'game'], 'ui_tap': ['all'], 'win': ['results']}
FONTS = [('Fredoka', 600, 'assets/fonts/Fredoka-SemiBold.ttf'), ('Fredoka', 700, 'assets/fonts/Fredoka-Bold.ttf'),
         ('Nunito', 400, 'assets/fonts/Nunito-Regular.ttf'), ('Nunito', 700, 'assets/fonts/Nunito-Bold.ttf')]


def mode_files(a):
    modes = a['modes']
    stems = [f"{a['id']}_{m}" for m in modes] if isinstance(modes, list) else [a['id']]
    return stems


def outputs(a):
    """Yields (svg_path, png_path, scale) for one logical asset."""
    for stem in mode_files(a):
        src = SVG / a['group'] / f'{stem}.svg'
        base = ASSETS / a['folder']
        for s in a['scales']:
            d = base if s == 1 else base / f'{s:.1f}x'
            yield src, d / f'{stem}.png', s


def render(job, env):
    src, dst, scale = job
    dst.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['rsvg-convert', '--zoom', str(scale), '--format', 'png', '--output', str(dst), str(src)],
                   check=True, env=env)


def build_manifest(meta):
    entries = []
    for a in meta['assets']:
        path = f"assets/{a['folder']}/{a['id']}" + ('_{mode}' if isinstance(a['modes'], list) else '') + '.png'
        entries.append(dict(id=a['id'], path=path, size=a['size'], anchor=a['anchor'], nineSlice=a['nineSlice'],
                            modes=a['modes'], scales=a['scales'], screens=a['screens'],
                            **({'notes': a['notes']} if a.get('notes') else {})))
    audio = [dict(id=k, path=f'assets/audio/{k}' + '.{format}', formats=['ogg', 'm4a'],
                  screens=AUDIO_SCREENS.get(k, ['game'])) for k in AUDIO]
    fonts = [dict(family=f, weight=w, path=p) for f, w, p in FONTS]
    return dict(version=1, note='Generated by tool/export_assets.py from design/svg. Do not edit by hand.',
                images=entries, audio=audio, fonts=fonts)


def expected_files(manifest):
    files = set()
    for e in manifest['images']:
        modes = e['modes'] if isinstance(e['modes'], list) else [None]
        for m in modes:
            rel = e['path'].replace('{mode}', m) if m else e['path']
            p = pathlib.PurePosixPath(rel)
            for s in e['scales']:
                files.add(str(p if s == 1 else p.parent / f'{s:.1f}x' / p.name))
    for e in manifest['audio']:
        for f in e['formats']:
            files.add(e['path'].replace('{format}', f))
    for f in manifest['fonts']:
        files.add(f['path'])
    return files


def check(manifest):
    expected = expected_files(manifest)
    actual = set()
    for sub in ['images', 'icons', 'audio', 'fonts']:
        for p in (ASSETS / sub).rglob('*'):
            if p.is_file() and p.suffix in ('.png', '.ogg', '.m4a', '.ttf'):
                actual.add(str(p.relative_to(ROOT)))
    missing = sorted(expected - actual)
    unlisted = sorted(actual - expected)
    return missing, unlisted


def main():
    meta = json.loads((SVG / 'meta.json').read_text())
    manifest = build_manifest(meta)
    if '--check' not in sys.argv:
        fc = tempfile.mkdtemp()
        conf = pathlib.Path(fc) / 'fonts.conf'
        conf.write_text(f'<?xml version="1.0"?><fontconfig><dir>{ASSETS / "fonts"}</dir>'
                        f'<cachedir>{fc}/cache</cachedir></fontconfig>')
        env = dict(os.environ, FONTCONFIG_FILE=str(conf))
        for sub in ['images', 'icons']:
            for p in (ASSETS / sub).rglob('*.png'):
                p.unlink()
        jobs = [j for a in meta['assets'] for j in outputs(a)]
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as ex:
            list(ex.map(lambda j: render(j, env), jobs))
        MANIFEST.write_text(json.dumps(manifest, indent=1) + '\n', encoding='utf-8')
        print(f'rendered {len(jobs)} PNGs; manifest lists {len(manifest["images"])} images, '
              f'{len(manifest["audio"])} sounds, {len(manifest["fonts"])} fonts')
    missing, unlisted = check(json.loads(MANIFEST.read_text()))
    for m in missing:
        print('MISSING', m)
    for u in unlisted:
        print('UNLISTED', u)
    print(f'check: {len(missing)} missing, {len(unlisted)} unlisted')
    sys.exit(1 if missing or unlisted else 0)


if __name__ == '__main__':
    main()
